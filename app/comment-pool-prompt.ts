export function buildCommentPoolCandidatePrompt(spec: CommentPoolSpec, existing: string[], count: number) {
  return `# 평가계획

과목: ${spec.subject}
단원: ${spec.unit}
영역: ${spec.domain}
평가목표: ${spec.goal}
평가관점: ${spec.perspective}
평가상의 유의점: ${spec.caution || "미입력"}
선택 수준: ${spec.level}
선택 수준 평가기준: ${spec.criterion}
기존 승인 문장: ${JSON.stringify(existing)}

# 요청

서로 다른 교과 평가 문장 후보 ${count}개를 작성한다.
기존 승인 문장과 완전히 같은 문장은 작성하지 않는다.

다음 JSON 형식으로 후보만 출력한다.

{
  "candidates": [
    { "text": "교과 평가 문장" }
  ]
}`;
}
